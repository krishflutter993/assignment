#include <iostream>
using namespace std;

int main()
{
    int num1, num2, sum;

    // Ask the user for two numbers
    cout << "Enter the two number: ";
    cin >> num1;
    cin >> num2;

    // Calculate the sum
    sum = num1 + num2;

    // Display the result
    cout << "the sum of numbers is: " << sum << endl;

    return 0;
}
